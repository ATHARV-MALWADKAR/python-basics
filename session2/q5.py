'''
Take a number as input. Print the result of that number raised to the power of 3
using the **. Also print what //7 and %7 give for the same number.
'''

number = int(input("Enter a number: "))
print(f"{number} raised to the power of 3 is {number ** 3}")
print(f"{number} // 7 = {number // 7}")
print(f"{number} % 7 = {number % 7}")
"""
Q1: Take two numbers as input from the user. Print their sum, difference,
product, and remainder.
"""


i1 = int(input("Enter the first number: "))
i2 = int(input("Enter the second number: "))

print("Sum:", i1 + i2)
print("Difference:", i1 - i2)
print("Product:", i1 * i2)
print("Remainder:", i1 % i2)
print("Division:", i1 / i2)